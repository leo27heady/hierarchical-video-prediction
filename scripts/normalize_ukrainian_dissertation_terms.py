def main() -> None:
    for path in sorted(SOURCE.glob("*.txt")):
        text = path.read_text(encoding="utf-8")
        updated = text
        for before, after in REPLACEMENTS:
            updated = updated.replace(before, after)
        if updated != text:
            path.write_text(updated, encoding="utf-8")
            print(path.name)


if __name__ == "__main__":
    main()
