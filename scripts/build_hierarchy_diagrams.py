from pathlib import Path
from html import escape
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'figures/restructured'

def label(x,y,text,size=20,weight='normal'):
    return f'<text x="{x}" y="{y}" font-size="{size}" font-weight="{weight}">{escape(text)}</text>'
def rect(x,y,w,h,color='#edf3f7'):
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="8" fill="{color}" stroke="#667789"/>'
def grid(x,y,n,color):
    return ''.join(f'<rect x="{x+i*72/n}" y="{y+j*72/n}" width="{72/n}" height="{72/n}" fill="{color}" stroke="#667789"/>' for i in range(n) for j in range(n))
def card(y,title,lines):
    s=rect(24,y,952,150)+label(44,y+30,title,23,'bold')
    for i,line in enumerate(lines):s+=label(44,y+64+i*30,line)
    return s
def save(name,height,content):
    OUT.mkdir(parents=True,exist_ok=True)
    (OUT/name).write_text(f'<svg xmlns="http://www.w3.org/2000/svg" width="1000" height="{height}" viewBox="0 0 1000 {height}"><rect width="1000" height="{height}" fill="white"/><g font-family="DejaVu Sans, Arial, sans-serif" fill="#172c3e">{content}</g></svg>\n',encoding='utf-8')
