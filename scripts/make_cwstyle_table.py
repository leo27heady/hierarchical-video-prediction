"""CW-VAE-style comparison table + degradation curves from ALL measured rollout npz.

Outputs (re-runnable; new arms/seeds auto-join as their npz land in logs_rhcp/):
  docs/CWSTYLE_TABLE.md            -- master config table (depth x factors x head x budget)
  docs/figures/fig12_cwstyle_curves.png -- fg-MSE + sharpness vs rollout horizon (the CW-VAE
                                      "how long do models keep their metrics" figure, with our
                                      protocol: fg-masked, persistence floor, AE sharp ceiling)

Presentation mirrors CW-VAE (Saxena et al. 2021) fig-style; metrics/pairing stay OURS (fg-MSE,
cluster-CI discipline lives in the compare logs -- this table reports arm-level values only,
seed-mean (min-max) where 2 seeds; regime disclosed per row; NO aggregate SSIM/PSNR).
CPU-only: safe to run while GPU experiments are live.
"""
import glob
import os
import re

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = os.path.join(os.path.dirname(__file__), "..")
LOGS = os.path.join(ROOT, "logs_rhcp")

# arm -> (ctx tokens, depth, temporal factor, spatial factor, head, note)
# depth counts latent context streams incl. fine (flat = 1). factors are per-stage (t = stride,
# s = spatial downsample per stage); "-" where no coarser stage exists.
ARMS_META = {
    "flat-short":   (512,  1, "-", "-", "diff", ""),
    "hier-short":   (480,  2, 1, 2, "diff", "6c+6f (span 6 < loop)"),
    "hier-s2-min":  (512,  2, 2, 2, "diff", "24c@s2+2f (span 48) [B1]"),
    "flat-min":     (896,  1, "-", "-", "diff", ""),
    "hier-min":     (896,  2, 1, 2, "diff", "48c+2f"),
    "strided-flat": (1088, 1, "4*", "-", "diff", "11 hist@s4+6f, span 48 [B2]"),
    "flat-budget":  (1152, 1, "-", "-", "diff", ""),
    "hier-long":    (1152, 2, 1, 2, "diff", "48c+6f (headline)"),
    "reg-flat":     (1152, 1, "-", "-", "reg", ""),
    "reg-long":     (1152, 2, 1, 2, "reg", "48c+6f"),
    "hier3":        (1152, 3, 1, 2, "diff", "48t+24c+9f (2x2/4x4/8x8) [B3]"),
    "spat18":       (672,  2, 1, 2, "diff", "18c+6f (W18 factorial)"),
    "spat18-reg":   (672,  2, 1, 2, "reg", "18c+6f"),
    "flat-c1":      (1792, 1, "-", "-", "diff", ""),
    "hier-c1":      (1792, 2, 1, 2, "diff", "48c+16f"),
    "flat-c2":      (2432, 1, "-", "-", "diff", ""),
    "hier-c2":      (2432, 2, 1, 2, "diff", "48c+26f"),
    "flat-long":    (3072, 1, "-", "-", "diff", "B8x60k regime"),
    "hier-rich":    (3072, 2, 1, 2, "diff", "48c+36f, B8x60k regime"),
}
# curves: which arms to draw (only those with npz present are drawn)
CURVE_ARMS = ["flat-budget", "hier-long", "reg-flat", "reg-long", "hier3", "strided-flat",
              "flat-long", "hier-min", "hier-s2-min"]
HBINS = [(1, 8), (9, 16), (17, 24), (25, 36), (37, 48), (49, 60), (61, 80), (81, 104),
         (105, 128), (129, 152)]
AE_SHARP_CEIL = 0.2412
C = {"flat-budget": "#264653", "hier-long": "#e76f51", "reg-flat": "#4a6fa5",
     "reg-long": "#e9c46a", "hier3": "#9b2226", "strided-flat": "#2a9d8f",
     "flat-long": "#6c757d", "hier-min": "#f4a261", "hier-s2-min": "#8338ec"}


def collect():
    rows = {}
    for p in sorted(glob.glob(os.path.join(LOGS, "rhvd_eval_*_s*.npz"))):
        m = re.match(r"rhvd_eval_(.+)_s(\d)(_60k)?\.npz$", os.path.basename(p))
        if not m:                     # skips _oracle/_smoke/_probe/_blind tags
            continue
        arm, seed, regime = m.group(1), int(m.group(2)), ("60k" if m.group(3) else "30k")
        # default-named npz of the two top-budget arms ARE the B8x60k regime (disclosed in T4)
        if arm in ("flat-long", "hier-rich") and regime == "30k":
            regime = "B8x60k"
        if arm not in ARMS_META or seed > 1:
            continue
        with np.load(p) as z:
            h, fg = z["h"], z["fg"]
            rows.setdefault((arm, regime), {})[seed] = dict(
                all=float(fg.mean()), sharp=float(z["sharp"].mean()),
                pers=float(z["pers_fg"].mean()),
                curve=[float(fg[(h >= lo) & (h <= hi)].mean()) for lo, hi in HBINS],
                sharp_curve=[float(z["sharp"][(h >= lo) & (h <= hi)].mean())
                             for lo, hi in HBINS])
    return rows


def fmt(vals):
    if len(vals) == 1:
        s = next(iter(vals.values()))
        return f"{s['all']:.4f} (1s)"
    a = [vals[s]["all"] for s in sorted(vals)]
    return f"{np.mean(a):.4f} ({min(a):.4f}–{max(a):.4f})"


def main():
    rows = collect()
    pers = np.mean([s["pers"] for v in rows.values() for s in v.values()])

    lines = [
        "# CW-style comparison table (auto-generated by scripts/make_cwstyle_table.py)",
        "",
        "Long-horizon rollout quality (ALL fg-MSE over 152 AR frames after 48-frame GT warmup,",
        "lower is better; seed-mean with min–max where 2 seeds). Depth 1 = flat (a 1-stage",
        "hierarchy); t/s = per-stage temporal/spatial downsampling factors. Regime disclosed —",
        "B16×30k unless noted; paired deltas + cluster CIs live in the compare logs, not here.",
        f"Persistence floor ≈ {pers:.4f}. EBT column: characterized negative at reachable scale",
        "(mean-collapse incl. the unchanged reference-repo control) — no rollout cells by design.",
        "",
        "| tokens | depth | t | s | head | arm | regime | ALL fg-MSE | sharp |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    order = sorted(rows.keys(), key=lambda k: (ARMS_META[k[0]][0], ARMS_META[k[0]][1],
                                               str(ARMS_META[k[0]][4]), k[1]))
    for arm, regime in order:
        tok, depth, tf, sf, head, note = ARMS_META[arm]
        v = rows[(arm, regime)]
        sharp = np.mean([s["sharp"] for s in v.values()])
        name = f"{arm}" + (f" — {note}" if note else "")
        lines.append(f"| {tok} | {depth} | {tf} | {sf} | {head} | {name} | {regime} "
                     f"| {fmt(v)} | {sharp:.4f} |")
    missing = [a for a in ARMS_META if not any(k[0] == a for k in rows)]
    if missing:
        lines += ["", f"Pending (no npz yet): {', '.join(sorted(missing))}."]
    out_md = os.path.join(ROOT, "docs", "CWSTYLE_TABLE.md")
    with open(out_md, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out_md} ({len(order)} rows)")

    # ---- fig12: degradation curves (CW-VAE-style "keep the metric over the horizon") ----
    fig, ax = plt.subplots(1, 2, figsize=(12.6, 4.8))
    xs = [0.5 * (lo + hi) for lo, hi in HBINS]
    for arm in CURVE_ARMS:
        key = next((k for k in rows if k[0] == arm and k[1] == "30k"),
                   next((k for k in rows if k[0] == arm), None))
        if key is None:
            continue
        v = rows[key]
        curve = np.mean([v[s]["curve"] for s in v], axis=0)
        scurve = np.mean([v[s]["sharp_curve"] for s in v], axis=0)
        tok, depth = ARMS_META[arm][0], ARMS_META[arm][1]
        lbl = f"{arm} (d{depth}, {tok} tok{', 60k' if key[1] == '60k' else ''})"
        ax[0].plot(xs, curve, "-o", ms=3.5, lw=1.6, color=C.get(arm), label=lbl)
        ax[1].plot(xs, scurve, "-o", ms=3.5, lw=1.6, color=C.get(arm), label=lbl)
    ax[0].axhline(pers, color="0.4", ls=":", lw=1.2)
    ax[0].text(xs[-1], pers + 0.002, "persistence", ha="right", fontsize=8, color="0.35")
    ax[0].set_xlabel("rollout horizon h (frames after GT warmup)")
    ax[0].set_ylabel("fg-MSE (lower better)")
    ax[0].set_title("A. Error growth over the rollout", fontsize=10)
    ax[1].axhline(AE_SHARP_CEIL, color="0.4", ls=":", lw=1.2)
    ax[1].text(xs[-1], AE_SHARP_CEIL - 0.012, "AE round-trip ceiling", ha="right",
               fontsize=8, color="0.35")
    ax[1].axhline(0.08, color="#9b2226", ls=":", lw=1.0)
    ax[1].text(xs[-1], 0.083, "collapse threshold", ha="right", fontsize=8, color="#9b2226")
    ax[1].set_xlabel("rollout horizon h")
    ax[1].set_ylabel("fg-sharpness (higher better)")
    ax[1].set_yscale("log")
    ax[1].set_title("B. Sharpness retention", fontsize=10)
    for a in ax:
        a.grid(alpha=0.25)
        a.legend(fontsize=7, framealpha=0.9)
    fig.suptitle("How long each configuration keeps its metrics over a 152-frame rollout "
                 "(loopmom; fg-masked; seed-mean)", fontsize=11)
    fig.tight_layout(rect=[0, 0, 1, 0.94])
    out_png = os.path.join(ROOT, "docs", "figures", "fig12_cwstyle_curves.png")
    fig.savefig(out_png, dpi=180)
    print(f"saved {out_png}")


if __name__ == "__main__":
    main()
